# ── Datetime validators ─────────────────────────────────────────────────────


class TestDatetimeValidators:

    def test_image_timestamp_from_datetime(self):
        dt = datetime.datetime(2025, 6, 15, 10, 30, 0, 500000) #500000 = 0.5seconds
        img = _make_image(imageTimestamp=dt)
        assert isinstance(img.imageTimestamp, datetime.datetime)
        assert img.imageTimestamp == dt

    def test_image_timestamp_from_iso_string(self):
        img = _make_image(imageTimestamp="2025-06-15T10:30:00.500Z")
        assert isinstance(img.imageTimestamp, datetime.datetime)
        assert img.imageTimestamp.year == 2025
        assert img.imageTimestamp.month == 6

    def test_image_timestamp_from_compact_string(self):
        img = _make_image(imageTimestamp="20250615T103000Z500")
        assert isinstance(img.imageTimestamp, datetime.datetime)
        assert img.imageTimestamp.microsecond == 500000

    def test_crop_timing_date_from_string(self):
        ct = CropTiming(type=CropTimingType.PLANTING_DATE, date="2025-03-01T08:00:00.000Z")
        assert isinstance(ct.date, datetime.datetime)

    def test_crop_timing_date_none_raises(self):
        """get_strptime does not handle None, so passing None to a validated datetime field raises."""
        with pytest.raises(Exception):
            CropTiming(type=CropTimingType.SOWING_DATE, date=None)

    def test_plotstate_valid_from_datetime(self):
        dt = datetime.datetime(2025, 1, 15, 10, 0)
        ps = _make_plotstate(validFrom=dt)
        assert ps.validFrom == dt

    def test_plotstate_valid_from_string(self):
        ps = _make_plotstate(validFrom="2025-01-15T10:30:00.000Z")
        assert isinstance(ps.validFrom, datetime.datetime)

    def test_dataset_issued_from_string(self):
        ds = _make_dataset(issued="2025-10-14T09:30:00.000Z")
        assert isinstance(ds.issued, datetime.datetime)

    def test_dataset_datetime_fields_none_raises(self):
        """get_strptime does not handle None, so explicitly passing None to validated datetime fields raises."""
        with pytest.raises(Exception):
            _make_dataset(issued=None, modified=None, startDate=None, endDate=None)


