# ── Helpers ──────────────────────────────────────────────────────────────────

def _make_camera(**overrides):
    defaults = dict(
        cameraName="cam01",
        cameraID="SN001",
        cameraModel="TestCam 1.0",
        cameraLensModel="TestLens 6mm",
        maxPixelX=1920,
        maxPixelY=1080,
        pixelSize=3.45,
        focalLength=6.0,
        subjectDistance=2.0,
    )
    defaults.update(overrides)
    return CameraMetadata(**defaults)


def _make_crop(**overrides):
    defaults = dict(cropName="wheat", cropCode="TRZAW")
    defaults.update(overrides)
    return CropMetadata(**defaults)


def _make_plotstate(**overrides):
    defaults = dict(stateName="plot1_state_1", hasCrop=_make_crop())
    defaults.update(overrides)
    return PlotStateMetadata(**defaults)


def _make_plot(**overrides):
    defaults = dict(
        plotName="plot1",
        bbox=["POLYGON((0 0, 1 0, 1 1, 0 1, 0 0))"],
        hasPlotState=_make_plotstate(),
    )
    defaults.update(overrides)
    return PlotMetadata(**defaults)


def _make_field(**overrides):
    defaults = dict(
        fieldName="field_a",
        bbox="POLYGON((0 0, 10 0, 10 10, 0 10, 0 0))",
        hasPlot=_make_plot(),
    )
    defaults.update(overrides)
    return FieldMetadata(**defaults)


def _make_sensor(**overrides):
    defaults = dict(hasCamera=_make_camera())
    defaults.update(overrides)
    return SensorMetadata(**defaults)


def _make_platform(**overrides):
    defaults = dict(platformName="robot1", hasSensor=_make_sensor())
    defaults.update(overrides)
    return PlatformMetadata(**defaults)


def _make_image(**overrides):
    defaults = dict(
        imageName="20250101T120000Z000_camid1_trigger000001_rgb.png",
        imageTimestamp=datetime.datetime(2025, 1, 1, 12, 0, 0),
        cameraID="SN001",
        fieldID="field_a_abc",
        plotID="plot1_abc",
        platformID="robot1_abc",
        baseQuaternionXYZW=[0.0, 0.0, 0.0, 1.0],
    )
    defaults.update(overrides)
    return ImageMetadata(**defaults)


def _make_dataset(**overrides):
    defaults = dict(
        title="Test dataset",
        description="A test dataset",
        identifier="test_001",
        creator=AgentMetadata(name="Tester"),
        numberOfImages=10,
        numberOfAnnotatedImages=5,
        hasField=_make_field(),
        hasPlatform=_make_platform(),
    )
    defaults.update(overrides)
    return DatasetMetadata(**defaults)


